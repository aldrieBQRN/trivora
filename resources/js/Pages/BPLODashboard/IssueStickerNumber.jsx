/**
 * Determine coding day and color scheme based on the last digit of the Sticker Number.
 * Conforms with Nasugbu Municipal Traffic Management Ordinance.
 */
function getCodingSchemeInfo(codingNumber, schemes = []) {
    if (!codingNumber) {
        return { day: 'Unassigned', scheme: 'Standard', colorClass: 'bg-slate-100 text-slate-700 border-slate-200', badgeClass: 'bg-slate-100 text-slate-700 border-slate-200' };
    }
    const clean = String(codingNumber).trim();
    const lastChar = clean.charAt(clean.length - 1);
    const lastDigit = parseInt(lastChar, 10);

    if (isNaN(lastDigit)) {
        return { day: 'Unassigned', scheme: 'Standard', colorClass: 'bg-slate-100 text-slate-700 border-slate-200', badgeClass: 'bg-slate-100 text-slate-700 border-slate-200' };
    }

    const matched = (schemes || []).find((s) =>
        Array.isArray(s.restricted_digits) && s.restricted_digits.map(Number).includes(lastDigit)
    );

    if (matched) {
        const day = (matched.restricted_days && matched.restricted_days[0]) ? matched.restricted_days[0] : 'Unrestricted';
        const digits = (matched.restricted_digits || []).join(' & ');
        return {
            day,
            digits,
            scheme: `${matched.name} Scheme`,
            hex: matched.color_hex,
            fineAmount: matched.fine_amount,
            badgeClass: 'border-slate-200/80',
            style: {
                backgroundColor: `${matched.color_hex}15`,
                color: '#1e293b',
                borderColor: `${matched.color_hex}40`,
            },
            dotStyle: {
                backgroundColor: matched.color_hex,
            },
        };
    }

    return { day: 'Unassigned', scheme: 'Standard', colorClass: 'bg-slate-100 text-slate-700 border-slate-200', badgeClass: 'bg-slate-100 text-slate-700 border-slate-200' };
}

