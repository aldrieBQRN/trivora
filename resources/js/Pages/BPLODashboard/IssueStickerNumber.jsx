                        const { success, error } = page.props.flash || {};
                        if (error) return;
                        Swal.fire({
                            title: 'Franchise Released!',
                            text: success || 'Unit advanced to TMO Final Confirmation.',
                            icon: 'success',
                            confirmButtonColor: '#059669',
                        });
